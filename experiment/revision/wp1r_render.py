"""Render WP-1R/WP-2R analysis JSONs into LaTeX macros and a results table.

Reads artifacts/wp1r_20260915/analysis_report.json and
artifacts/wp1r_20260915/wp2r_selector_report.json and writes
paper/latex/wp1r_numbers.tex (\\newcommand macros) and
paper/latex/wp1r_policy_table.tex.  Every number in the WP-1R paper section
comes from this file; no hand-copied values.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WP1R = ROOT / 'artifacts/wp1r_20260915'
TEX = ROOT / 'paper' / 'latex'


def pp(x, digits=2):
    """Format a probability as percentage points with fixed digits."""
    return f'{100 * x:.{digits}f}'


def macro(name, value):
    return f'\\newcommand{{\\{name}}}{{{value}}}'


def policy_table(sel):
    acc = sel['accuracy']
    rows = []
    for name, label in [('bare', r'\bare{} (fixed)'),
                        ('dev_fixed', 'dev-fixed'),
                        ('random_fixed', 'random (pre-fixed)'),
                        ('M1b', 'M1b (dev-fixed + bare fallback)'),
                        ('pi_Z', r'$\pi_Z$ (frozen selector)')]:
        a = acc[name]
        row = f"{label} & {pp(a['accuracy'])}"
        if 'paired_vs_dev_fixed' in a:
            p = a['paired_vs_dev_fixed']
            row += (f" & {pp(p['mean'])} "
                    f"[{pp(p['ci95'][0])}, {pp(p['ci95'][1])}]")
        else:
            row += ' & ---'
        rows.append(row + r' \\')
    return '\n'.join([
        r'\begin{tabular}{@{}lcc@{}}',
        r'\toprule',
        r'Policy & Eval acc.\ (\%) & $\Delta$ vs dev-fixed (pp) [95\% CI] \\',
        r'\midrule',
        *rows,
        r'\bottomrule',
        r'\end{tabular}',
    ]) + '\n'


def main():
    report = json.loads((WP1R / 'analysis_report.json')
                        .read_text(encoding='utf-8'))
    sel_path = WP1R / 'wp2r_selector_report.json'
    sel = json.loads(sel_path.read_text(encoding='utf-8')) \
        if sel_path.exists() else None
    lines = ['% Auto-generated by experiment/revision/wp1r_render.py.',
             '% Do not edit by hand; regenerate after re-running the analysis.']

    a86 = report['E2_A86_clone_null']
    lines += [
        macro('WpAReal', pp(a86['A_real'])),
        macro('WpAClone', pp(a86['A_clone_obs'])),
        macro('WpADiff', pp(a86['D'])),
        macro('WpADiffCI', f"[{pp(a86['D_ci95'][0])}, {pp(a86['D_ci95'][1])}]"),
        macro('WpAPerm', f"{a86['p_perm']:.4f}".lstrip('0')),
        macro('WpAState', a86['state'].replace('_', r'\_')),
        macro('WpANtasksReal', a86['n_tasks_real']),
        macro('WpANtasksClone', a86['n_tasks_clone']),
        macro('WpANtasksPaired', a86['n_tasks_paired']),
        macro('WpExclReal', f"{100 * a86['excluded_frac_real']:.1f}"),
        macro('WpExclClone', f"{100 * a86['excluded_frac_clone']:.1f}"),
        macro('WpImputedD', pp(a86['sensitivity_imputed']['D'])),
        macro('WpImputedNPaired', a86['sensitivity_imputed']['n_tasks_paired']),
    ]
    conflict = report.get('E2_sensitivity_double_executed_conflicts')
    if conflict is not None:
        lines += [
            macro('WpConflictD', pp(conflict['D'])),
            macro('WpConflictCI',
                  f"[{pp(conflict['D_ci95'][0])}, {pp(conflict['D_ci95'][1])}]"),
            macro('WpConflictNExcluded', conflict['n_cells_excluded']),
        ]
    else:
        lines += [macro('WpConflictD', r'\text{---}'),
                  macro('WpConflictCI', r'\text{---}'),
                  macro('WpConflictNExcluded', 0)]

    s3 = report['E1_C-rank_E2_C-comp']
    lines += [
        macro('WpCrankState', s3['stable_ranking']['state'].replace('_', r'\_')),
        macro('WpCcompState', s3['stable_complementarity']['state'].replace('_', r'\_')),
    ]
    sc = s3['stable_complementarity']
    if sc.get('H_stable') is not None:
        lines += [macro('WpHstable', pp(sc['H_stable'])),
                  macro('WpHstableCI',
                        f"[{pp(sc['H_ci95'][0])}, {pp(sc['H_ci95'][1])}]")]
    else:
        lines += [macro('WpHstable', r'\text{abstained}'),
                  macro('WpHstableCI', r'\text{---}')]

    dedup = report['dedup_eval_real']
    lines += [
        macro('WpRowsRead', f"{dedup['rows_read']:,}"),
        macro('WpMigrationCopies', f"{dedup['identical_copies']:,}"),
        macro('WpDoubleExec', len(dedup['both_completed_differ'])),
        macro('WpUnknownCarried', dedup['unknown_carried']),
        macro('WpCompletedBeatsUnknown', dedup['completed_beats_unknown']),
        macro('WpUnknownThenCompleted', dedup['unknown_then_completed']),
    ]
    dedup_c = report.get('dedup_eval_clone')
    if dedup_c:
        lines += [macro('WpCloneRowsRead', f"{dedup_c['rows_read']:,}"),
                  macro('WpCloneMigrationCopies',
                        f"{dedup_c['identical_copies']:,}"),
                  macro('WpCloneUnique', f"{dedup_c['unique_keys']:,}"),
                  macro('WpCloneConflicts', len(dedup_c['both_completed_differ']))]
    else:
        lines += [macro('WpCloneRowsRead', r'\text{---}'),
                  macro('WpCloneMigrationCopies', r'\text{---}'),
                  macro('WpCloneUnique', r'\text{---}'),
                  macro('WpCloneConflicts', r'\text{---}')]

    e4 = report['E4_accounting']['_total']
    lines += [
        macro('WpLogicalCalls', f"{e4['logical_calls']:,}"),
        macro('WpHttpAttempts', f"{e4['http_attempts']:,}"),
        macro('WpTotalTokens', f"{e4['known_total_tokens'] / 1e6:.1f}\\,M"),
        macro('WpCostCny', f"{e4['conservative_cost_ceiling_cny']:,}"),
    ]

    if sel is not None:
        acc = sel['accuracy']
        summ = sel['summary']
        lines += [
            macro('WpDevFixedMember', summ['dev_fixed_member'].replace('_', r'\_')),
            macro('WpAbstainRate', pp(summ['abstain_rate_pi_Z'])),
            macro('WpPiZAcc', pp(acc['pi_Z']['accuracy'])),
            macro('WpDevFixedAcc', pp(acc['dev_fixed']['accuracy'])),
            macro('WpBareAcc', pp(acc['bare']['accuracy'])),
            macro('WpPiZDiff', pp(acc['pi_Z']['paired_vs_dev_fixed']['mean'])),
            macro('WpPiZDiffCI',
                  f"[{pp(acc['pi_Z']['paired_vs_dev_fixed']['ci95'][0])}, "
                  f"{pp(acc['pi_Z']['paired_vs_dev_fixed']['ci95'][1])}]"),
            macro('WpRandomDiff', pp(acc['random_fixed']['paired_vs_dev_fixed']['mean'])),
            macro('WpRandomCI',
                  f"[{pp(acc['random_fixed']['paired_vs_dev_fixed']['ci95'][0])}, "
                  f"{pp(acc['random_fixed']['paired_vs_dev_fixed']['ci95'][1])}]"),
            macro('WpEbZero', 'yes' if all(
                acc[k].get('paired_vs_dev_fixed', {}).get('mean', 0) == 0
                and acc[k].get('paired_vs_dev_fixed', {}).get('harm_rate', 0) == 0
                for k in ('pi_Z', 'bare', 'dev_fixed', 'M1b')) else 'no'),
        ]
        (TEX / 'wp1r_policy_table.tex').write_text(
            policy_table(sel), encoding='utf-8')
    else:
        for name in ('WpDevFixedMember', 'WpAbstainRate', 'WpPiZAcc',
                     'WpDevFixedAcc', 'WpBareAcc', 'WpPiZDiff'):
            lines.append(macro(name, r'\text{---}'))
        lines.append(macro('WpPiZDiffCI', r'\text{---}'))
        lines.append(macro('WpRandomDiff', r'\text{---}'))
        lines.append(macro('WpRandomCI', r'\text{---}'))
        lines.append(macro('WpEbZero', r'\text{---}'))

    (TEX / 'wp1r_numbers.tex').write_text('\n'.join(lines) + '\n',
                                         encoding='utf-8')
    print('wrote', TEX / 'wp1r_numbers.tex',
          'and wp1r_policy_table.tex' if sel else '(selector report pending)')


if __name__ == '__main__':
    main()
